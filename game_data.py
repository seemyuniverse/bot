def loot_weights():
    """아이템 이름별 확률 표. 등급 확률을 그 등급 아이템 수로 똑같이 나눈 값이다(전체 합 100)."""
    result = {}
    for grade, items in LOOT.items():
        each = GRADE_PROBABILITY[grade] / len(items)
        for name, _desc in items:
            result[name] = round(each, 4)
    return result


def pick(options):
    """(값, 확률) 목록에서 확률대로 하나 뽑는다."""
    values, weights = zip(*options)
    return random.choices(values, weights=weights, k=1)[0]


def eul_reul(word):
    """마지막 글자에 받침이 있으면 '을', 없으면 '를'을 붙여서 돌려준다."""
    last = word[-1]
    if "가" <= last <= "힣" and (ord(last) - 0xAC00) % 28:
        return word + "을"
    return word + "를"

